def generate_report(task, gate_status, diff_hash, verify_hash, mutants, survivors, out_path):
    killed = sum(1 for m in mutants if m.get("status") == "KILLED")
    total = len(mutants)
    score_str = f"{(killed / total * 100):.1f}%" if total > 0 else "N/A"

    mutant_rows = []
    for idx, m in enumerate(mutants, 1):
        status = m.get("status", "UNKNOWN")
        color = "green" if status == "KILLED" else "red"
        row = f"""    <tr>
      <td>{idx}</td>
      <td><code>{m.get('operator')}</code></td>
      <td>L{m.get('line')}</td>
      <td><code>{m.get('text')}</code></td>
      <td><font color="{color}"><b>{status}</b></font></td>
    </tr>"""
        mutant_rows.append(row)

    survivor_rows = []
    if survivors:
        for s in survivors:
            row = f"""    <tr>
      <td><code>{s.get('operator')} at L{s.get('line')}</code></td>
      <td>{s.get('label', 'unlabeled')}</td>
      <td>{s.get('reason', 'None')}</td>
    </tr>"""
            survivor_rows.append(row)
    else:
        survivor_rows.append("    <tr><td colspan=\"3\"><i>No surviving mutants. All mutants killed.</i></td></tr>")

    base_content = HTML_TEMPLATE.format(
        task=task,
        gate_status=gate_status,
        mutation_score=score_str,
        killed_count=killed,
        total_count=total,
        diff_hash=diff_hash,
        verify_hash=verify_hash,
        report_hash="PENDING_HASH",
        mutant_rows="\n".join(mutant_rows),
        survivor_rows="\n".join(survivor_rows)
    )

    digest = hashlib.sha256(base_content.encode("utf-8")).hexdigest()
    final_content = base_content.replace("PENDING_HASH", digest)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(final_content)

    return out_path, digest

