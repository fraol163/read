package orchestrator

import (
	"io"
	"time"
)

// PipelineConfig contains all options for running the autonomous agent pipeline.
type PipelineConfig struct {
	Workspace           string        `json:"workspace"`
	Prompt              string        `json:"prompt"`
	HarnessID           string        `json:"harness_id,omitempty"`
	AutoApprove         bool          `json:"auto_approve"`
	TimeoutSeconds      int           `json:"timeout_seconds,omitempty"`
	EngineBin           string        `json:"engine_bin,omitempty"`
	TestCommand         string        `json:"test_command,omitempty"`
	CustomHarnessConfig string        `json:"custom_harness_config,omitempty"`
	Stdout              io.Writer     `json:"-"`
	Stderr              io.Writer     `json:"-"`
	Timeout             time.Duration `json:"-"`
}

// StageStatus represents the execution status of a single pipeline stage.
type StageStatus string

const (
	StageStatusPending StageStatus = "pending"
	StageStatusRunning StageStatus = "running"
	StageStatusPassed  StageStatus = "passed"
	StageStatusFailed  StageStatus = "failed"
	StageStatusSkipped StageStatus = "skipped"
)

// MutantRecord represents a single AST mutant generated by read-engine.
type MutantRecord struct {
	ID           int    `json:"id"`
	OriginalLine string `json:"original_line"`
	MutatedLine  string `json:"mutated_line"`
	LineNumber   int    `json:"line_number"`
	Operator     string `json:"operator"`
	FilePath     string `json:"file_path,omitempty"`
}

// MutantExecutionResult tracks the outcome of testing a single mutant.
type MutantExecutionResult struct {
	Mutant  MutantRecord `json:"mutant"`
	Killed  bool         `json:"killed"`
	Output  string       `json:"output,omitempty"`
	Timeout bool         `json:"timeout"`
}

// PipelineResult encapsulates the complete forensic outcome of the pipeline.
type PipelineResult struct {
	Success        bool                    `json:"success"`
	TaskID         string                  `json:"task_id"`
	ContractHash   string                  `json:"contract_hash"`
	BaseCommit     string                  `json:"base_commit"`
	DiffHash       string                  `json:"diff_hash,omitempty"`
	VerifyHash     string                  `json:"verify_hash,omitempty"`
	HarnessUsed    string                  `json:"harness_used,omitempty"`
	MutationScore  float64                 `json:"mutation_score"`
	MutantsTotal   int                     `json:"mutants_total"`
	MutantsKilled  int                     `json:"mutants_killed"`
	FinalState     string                  `json:"final_state"`
	StageResults   map[string]StageStatus  `json:"stage_results"`
	Diagnostics    string                  `json:"diagnostics,omitempty"`
	Error          string                  `json:"error,omitempty"`
	MutantResults  []MutantExecutionResult `json:"mutant_results,omitempty"`
	LogFilePath    string                  `json:"log_file_path,omitempty"`
	ContextFiles   int                     `json:"context_files"`
	ExecutionTimeMs int64                  `json:"execution_time_ms"`
}
