#!/usr/bin/env python3
import subprocess, os, sys

repo_dir = "/tmp/test_outside_repo"
engine_bin = "/home/renan/Downloads/me/methodology_session/read/bin/read-engine"

if not os.path.exists(repo_dir):
    print(f"ERROR: Repository {repo_dir} does not exist.")
    sys.exit(1)

# Step 1: Run read-engine mutate on staged diff
print("[STEP 1] Generating diff mutants via read-engine...")
res_mutate = subprocess.run([engine_bin, "mutate"], cwd=repo_dir, capture_output=True, text=True)
print(res_mutate.stdout)
if res_mutate.returncode != 0:
    print(f"ERROR: read-engine mutate exited with {res_mutate.returncode}")
    sys.exit(1)

# Step 2: Evaluate mutants against pytest
file_path = os.path.join(repo_dir, "backend/resources/preview.py")
orig_content = open(file_path).read()

# 8 mutants generated by read-engine
mutants = [
    (1, 259, "return TextPreview(False, metrics=metrics, message=f\"text preview failed: {e}\")", "return TextPreview(True, metrics=metrics, message=f\"text preview failed: {e}\")", "FLIP_BOOL_FALSE"),
    (2, 259, "return TextPreview(False, metrics=metrics, message=f\"text preview failed: {e}\")", "return None", "RETURN_NONE"),
    (3, 260, "return TextPreview(True, lines=lines, metrics=metrics, message=\"text preview\")", "return TextPreview(False, lines=lines, metrics=metrics, message=\"text preview\")", "FLIP_BOOL_TRUE"),
    (4, 260, "return TextPreview(True, lines=lines, metrics=metrics, message=\"text preview\")", "return None", "RETURN_NONE"),
    (5, 272, "if not line.strip() or line.startswith(\"#\"):", "if not line.strip() and line.startswith(\"#\"):", "LOGICAL_OR_TO_AND"),
    (6, 285, "if a < 128.0:", "if a >= 128.0:", "INVERT_LT"),
    (7, 294, "if count != cols * rows:", "if count == cols * rows:", "INVERT_NEQ"),
    (8, 296, "return [\"\".join(ch if ch is not None else \" \" for ch in row).rstrip() for row in grid]", "return None", "RETURN_NONE")
]

print("[STEP 2] Running pytest against each mutant...")
results = []
for mid, line_no, orig, rep, op in mutants:
    if orig not in orig_content:
        print(f"ERROR: Target line for mutant {mid} not found!")
        sys.exit(1)
    mutated = orig_content.replace(orig, rep, 1)
    with open(file_path, "w") as f:
        f.write(mutated)
    
    test_run = subprocess.run(["pytest", "tests/test_m7_vector_preview.py"], cwd=repo_dir, capture_output=True, text=True)
    if test_run.returncode != 0:
        status = "KILLED (test failure)"
    else:
        status = "SURVIVED (tests passed without detecting mutant)"
    results.append((mid, line_no, op, status))

# Restore unmodified file
with open(file_path, "w") as f:
    f.write(orig_content)

print()
print("=== RESULTS ===")
killed = 0
survived = 0
for mid, line_no, op, status in results:
    print(f"Mutant #{mid} [L{line_no} {op}]: {status}")
    if "KILLED" in status:
        killed += 1
    else:
        survived += 1

score = (killed / len(results)) * 100.0
print()
print(f"Final Outside Repository Mutation Score: {score:.1f}% ({killed}/{len(results)} killed, {survived}/{len(results)} survived)")
if score < 100.0:
    print("AROP GATE RESULT: FAILED (Exit Code: 1)")
    sys.exit(1)
else:
    print("AROP GATE RESULT: PASSED (Exit Code: 0)")
    sys.exit(0)
